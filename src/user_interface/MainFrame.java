    private void initializePageTitle(){
        switch(currentState){
            case 1:
                setPageTitle("Dash Board");
                break;
            case 2:
                setPageTitle("Add Transaction");
                break;
            case 3:
                setPageTitle("Chart of Accounts");
                break;
            case 4:
                setPageTitle("Begining Trial Balance");
                break;
            case 5:
                setPageTitle("Credit Tracking");
                break;
            case 6:
                setPageTitle("Inventory");
                break;
            case 7:
                setPageTitle("General Journal");
                break;
            case 8:
                setPageTitle("General Ledger");
                break;
            case 9:
                setPageTitle("Unadjusted Trial Balance");
                break;
            case 10:
                setPageTitle("Statements");
                break;
            case 11:
                setPageTitle("About");
                break;
        }
    }
    
    private void setPageTitle(String title){
        titleLabel.setText(title);
        int size = 48;
        Font font = new Font("Segoe UI", Font.BOLD, size);
        while(size > 24 && titleLabel.getFontMetrics(font).stringWidth(title) > 560){
            size -= 2;
            font = new Font("Segoe UI", Font.BOLD, size);
        }
        titleLabel.setFont(font);
    }

    // one page per sidebar button, in the same order as the currentState numbers above
    private void initPages(){
        cards = new java.awt.CardLayout();
        mainDisplayPanel.setLayout(cards);
        pages = java.util.List.of(
                new DashBoardPanel(),               // 1
                new AddTransactionPanel(),          // 2
                new ChartOfAccountsPanel(),         // 3
                new TrialBalancePanel(true),        // 4 Begining Trial Balance
                new CreditTrackingPanel(),          // 5
                new InventoryPanel(),               // 6
                new GeneralJournalPanel(),          // 7
                new GeneralLedgerPanel(),           // 8
                new TrialBalancePanel(false),       // 9 Unadjusted Trial Balance
                new StatementsPanel(),              // 10
                new AboutPanel());                  // 11
        for(int i = 0; i < pages.size(); i++){
            mainDisplayPanel.add(pages.get(i), String.valueOf(i + 1));
        }

        dashBoardButton.addActionListener(e -> showPage(1));
        addTransactionButton.addActionListener(e -> showPage(2));
        chartOfAccountsButton.addActionListener(e -> showPage(3));
        beginingTrialBalanceButton.addActionListener(e -> showPage(4));
        creditTrackingButton.addActionListener(e -> showPage(5));
        inventoryButton.addActionListener(e -> showPage(6));
        generalJournalButton.addActionListener(e -> showPage(7));
        generalLedgerButton.addActionListener(e -> showPage(8));
        unadjustedTrialBalanceButton.addActionListener(e -> showPage(9));
        statementsButton.addActionListener(e -> showPage(10));
        aboutButton.addActionListener(e -> showPage(11));
    }

    private void showPage(int state){
        currentState = state;
        initializePageTitle();
        pages.get(state - 1).refresh();
        cards.show(mainDisplayPanel, String.valueOf(state));
    }
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
